// Regenerates .github/ISSUE_TEMPLATE/language-list-change.yml from owners.json and each environment's values.yaml.
// Run: node tools/generate_issue_form.js   (tools/local_test.js fails if the committed form is out of date)
const fs = require('fs');
const path = require('path');
const { loadServiceConfig } = require('../scripts/language-list-request.js');

const root = path.resolve(__dirname, '..');
const FORM = path.join(root, '.github/ISSUE_TEMPLATE/language-list-change.yml');

function buildForm() {
  const products = Object.keys(JSON.parse(fs.readFileSync(path.join(root, 'language-lists/owners.json'), 'utf8')));
  const envs = fs.readdirSync(path.join(root, 'environments')).sort();
  // Union across environments; the bot still checks each environment separately.
  const countries = new Map();
  const locales = new Map();
  for (const env of envs) {
    const cfg = loadServiceConfig(root, env);
    for (const [c, r] of Object.entries(cfg.countries)) countries.set(c, r);
    for (const langs of Object.values(cfg.regions)) for (const l of langs) locales.set(l.name, l.englishName);
  }
  const countryOpts = [...countries].sort(([a], [b]) => a.localeCompare(b)).map(([c, r]) => `${c} (region ${r})`);
  const localeOpts = [...locales].sort(([a], [b]) => a.localeCompare(b)).map(([n, e]) => `${n} - ${e}`);
  const opt = (items) => items.map((i) => `        - "${i}"`).join('\n');
  const envOpt = envs.map((e) => `        - label: ${e}`).join('\n');
  return `# Generated by tools/generate_issue_form.js - edit owners.json or environments/*/values.yaml instead.
name: Language list change
description: Request a change to the languages offered for a country in your product.
title: "[language-list] "
labels: ["language-list-request"]
body:
  - type: markdown
    attributes:
      value: |
        Only people listed for the product in \`language-lists/owners.json\` can request changes.
        A bot validates the request and opens a pull request; a platform maintainer reviews and merges it.
  - type: dropdown
    id: product
    attributes:
      label: Product
      options:
${opt(products)}
    validations:
      required: true
  - type: checkboxes
    id: environments
    attributes:
      label: Environments
      description: Pick at least one.
      options:
${envOpt}
  - type: dropdown
    id: change
    attributes:
      label: Change
      options:
        - "Set languages for a country"
        - "Remove a country"
    validations:
      required: true
  - type: dropdown
    id: country
    attributes:
      label: Country
      options:
${opt(countryOpts)}
    validations:
      required: true
  - type: dropdown
    id: locales
    attributes:
      label: Locales
      description: Required for Set languages. Pick every language the country should offer; they must be supported in the country's region.
      multiple: true
      options:
${opt(localeOpts)}
    validations:
      required: false
  - type: textarea
    id: reason
    attributes:
      label: Reason
      description: Why is this change needed?
    validations:
      required: false
`;
}

module.exports = { buildForm, FORM };

if (require.main === module) {
  fs.writeFileSync(FORM, buildForm());
  console.log(`wrote ${path.relative(root, FORM)}`);
}
